#!/usr/bin/env node
// Bundle the typed canvas analyzer and its shared digest for page.evaluate.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [resolve(root, "src/review/compare-pngs.browser.ts")],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "browserComparison",
  target: "es2022",
  platform: "browser",
  legalComments: "none",
});
const code = result.outputFiles[0].text;
writeFileSync(
  resolve(root, "src/review/compare-pngs.browser.generated.ts"),
  `// AUTO-GENERATED by scripts/build-compare-pngs-browser.mjs. Edit compare-pngs.browser.ts instead.\nexport const BROWSER_COMPARISON_JS: string = ${JSON.stringify(code)};\n`,
);
