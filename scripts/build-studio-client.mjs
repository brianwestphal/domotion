#!/usr/bin/env node

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { bundleKerfClient } from "./bundle-kerf-client.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(root, "src/studio/client.tsx");
const output = resolve(root, "src/studio/client.bundle.generated.ts");

// The shared step also folds the client's @kerfjs/ui CSS into the bundle
// (docs/273-ui-conventions.md).
const { js: code } = await bundleKerfClient({
  entry,
  sourcemap: process.env.DOMOTION_BROWSER_COVERAGE === "1" ? "inline" : false,
});
const generated = [
  "// AUTO-GENERATED by scripts/build-studio-client.mjs — do NOT edit by hand.",
  "// The source lives at src/studio/client.tsx; rerun the build to regenerate.",
  "",
  `export const STUDIO_CLIENT_JS: string = ${JSON.stringify(code)};`,
  "",
].join("\n");
writeFileSync(output, generated);
process.stdout.write(`[build-studio-client] wrote ${output} (${(code.length / 1024).toFixed(1)} KB bundle)\n`);
