#!/usr/bin/env node

import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(root, "src/studio/client.tsx");
const output = resolve(root, "src/studio/client.bundle.generated.ts");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  target: "es2022",
  platform: "browser",
  jsx: "automatic",
  jsxImportSource: "kerfjs",
  legalComments: "none",
  minify: false,
  treeShaking: true,
});

const code = result.outputFiles[0].text;
const generated = [
  "// AUTO-GENERATED by scripts/build-studio-client.mjs — do NOT edit by hand.",
  "// The source lives at src/studio/client.tsx; rerun the build to regenerate.",
  "",
  `export const STUDIO_CLIENT_JS: string = ${JSON.stringify(code)};`,
  "",
].join("\n");
writeFileSync(output, generated);
process.stdout.write(`[build-studio-client] wrote ${output} (${(code.length / 1024).toFixed(1)} KB bundle)\n`);
