import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(import.meta.dirname, '..');
const dictionarySource = path.join(root, 'external/chromium/third_party/blink/renderer/platform/text/mathml_operator_dictionary.cc');
const characterSource = path.join(root, 'external/chromium/third_party/blink/renderer/platform/text/character.cc');
const output = path.join(root, 'src/generated/mathml-operator-dictionary.ts');

const dictionary = fs.readFileSync(dictionarySource, 'utf8');
const character = fs.readFileSync(characterSource, 'utf8');
const compactBody = /kCompactDictionary[\s\S]*?\(\s*\{([\s\S]*?)\}\);/.exec(dictionary)?.[1];
if (compactBody == null) throw new Error('Blink compact MathML dictionary not found');
const entries = [...compactBody.matchAll(/\{(0x[0-9A-F]+),\s*(\d+)\}/g)]
  .map((match) => `[${Number(match[1])},${Number(match[2])}]`);
if (entries.length < 200) throw new Error(`unexpected compact dictionary size: ${entries.length}`);
const inlineBody = /kStretchyOperatorWithInlineAxis\[\]\{([\s\S]*?)\};/.exec(character)?.[1];
if (inlineBody == null) throw new Error('Blink inline-axis stretchy table not found');
const inline = [...inlineBody.matchAll(/0x[0-9A-F]+/g)].map((match) => Number(match[0]));
const sourceRevision = '7d859f271cbda744098ac69f44978d4edfa62be3';

const generated = `// Generated by tools/generate-mathml-operator-dictionary.mjs. Do not edit.
// Chromium source: ${sourceRevision}

export const BLINK_MATHML_COMPACT_DICTIONARY = [
  ${entries.join(',')}
] as const;

export const BLINK_MATHML_INLINE_AXIS_STRETCHY = new Set<number>([
  ${inline.map((cp) => `0x${cp.toString(16)}`).join(',')}
]);

export const BLINK_MATHML_DICTIONARY_SOURCE = ${JSON.stringify(sourceRevision)};
`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) {
    console.error('Generated MathML operator dictionary is stale. Run npm run mathml:operator-dictionary:generate');
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, generated);
  console.log(`wrote ${path.relative(root, output)} (${entries.length} ranges, ${inline.length} inline-axis entries)`);
}
