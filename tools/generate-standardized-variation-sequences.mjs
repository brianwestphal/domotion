#!/usr/bin/env node
// Generate Blink's standardized variation-sequence membership table from the
// local Chromium checkout. The generated runtime file is committed, so package
// consumers do not need the checkout.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root,
  "external/chromium/third_party/blink/renderer/platform/text/character_variation_sequences.cc");
const outputPath = resolve(root, "src/render/standardized-variation-sequences.generated.ts");
const source = readFileSync(sourcePath, "utf8");
const start = source.indexOf("kStandardizedVariationSequences");
const end = source.indexOf("bool Character::IsStandardizedVariationSequence", start);
if (start < 0 || end < 0) throw new Error("Blink standardized variation-sequence table not found");

const values = [...source.slice(start, end).matchAll(/\\U([0-9A-F]{8})\\U([0-9A-F]{8})/g)]
  .map((match) => {
    const base = Number.parseInt(match[1], 16);
    const selector = Number.parseInt(match[2], 16);
    return base * 0x110000 + selector;
  })
  .sort((a, b) => a - b);

if (values.length === 0 || new Set(values).size !== values.length) {
  throw new Error("Blink standardized variation-sequence table is empty or contains duplicates");
}

const lines = [];
for (let i = 0; i < values.length; i += 12) {
  lines.push(`  ${values.slice(i, i + 12).join(", ")},`);
}
writeFileSync(outputPath, `// Generated by tools/generate-standardized-variation-sequences.mjs\n` +
  `// from Chromium's character_variation_sequences.cc. Do not edit by hand.\n` +
  `export const STANDARDIZED_VARIATION_SEQUENCES: readonly number[] = [\n${lines.join("\n")}\n];\n`);
console.log(`wrote ${values.length} standardized variation sequences to ${outputPath}`);
